// Accurate weighted random item picker based on item.chance (0..100)
export function rollCaseDrop(caseDef: CaseDefinition): SkinItem {
  const roll = Math.random() * 100 // 0.00 to 100.00
  let cumulative = 0

  for (const item of caseDef.items) {
    cumulative += item.chance
    if (roll <= cumulative) {
      return item
    }
  }

  // Fallback to last item or cheapest
  return caseDef.items[0]
}
